// Command protogen parses Go protocol frame definitions and generates
// strongly-typed client constants for TypeScript and Dart.
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

type constantDef struct {
	Name    string
	Value   string
	Comment string
}

func main() {
	sourcePath := flag.String("source", "pkg/protocol/frames.go", "Path to source frames.go")
	tsOut := flag.String("ts-out", "", "Output path for TypeScript file")
	dartOut := flag.String("dart-out", "", "Output path for Dart file")
	flag.Parse()

	fset := token.NewFileSet()
	node, err := parser.ParseFile(fset, *sourcePath, nil, parser.ParseComments)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error parsing source file: %v\n", err)
		os.Exit(1)
	}

	var frames []constantDef
	var contentTypes []constantDef

	for _, decl := range node.Decls {
		genDecl, ok := decl.(*ast.GenDecl)
		if !ok || genDecl.Tok != token.CONST {
			continue
		}

		for _, spec := range genDecl.Specs {
			valSpec, ok := spec.(*ast.ValueSpec)
			if !ok {
				continue
			}

			for i, name := range valSpec.Names {
				var valStr string
				if i < len(valSpec.Values) {
					if basicLit, ok := valSpec.Values[i].(*ast.BasicLit); ok {
						valStr = basicLit.Value
					}
				}

				comment := ""
				if valSpec.Comment != nil {
					comment = strings.TrimSpace(valSpec.Comment.Text())
				}

				def := constantDef{
					Name:    name.Name,
					Value:   valStr,
					Comment: comment,
				}

				if strings.HasPrefix(name.Name, "Frame") {
					frames = append(frames, def)
				} else if strings.HasPrefix(name.Name, "Content") {
					contentTypes = append(contentTypes, def)
				}
			}
		}
	}

	if *tsOut != "" {
		if err := generateTypeScript(*tsOut, frames, contentTypes); err != nil {
			fmt.Fprintf(os.Stderr, "Error generating TypeScript: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("Generated TypeScript frames: %s\n", *tsOut)
	}

	if *dartOut != "" {
		if err := generateDart(*dartOut, frames, contentTypes); err != nil {
			fmt.Fprintf(os.Stderr, "Error generating Dart: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("Generated Dart frames: %s\n", *dartOut)
	}
}

// generateTypeScript emits strongly-typed TypeScript constants from protocol definitions.
func generateTypeScript(outPath string, frames, contentTypes []constantDef) error {
	var sb strings.Builder
	sb.WriteString("// Code generated by pulse protogen. DO NOT EDIT.\n\n")

	sb.WriteString("// Wire protocol frame type codes\n")
	for _, f := range frames {
		if f.Comment != "" {
			sb.WriteString(fmt.Sprintf("// %s\n", f.Comment))
		}
		sb.WriteString(fmt.Sprintf("export const %s = %s;\n", f.Name, f.Value))
	}

	sb.WriteString("\n// Standard IM Content Types\n")
	for _, c := range contentTypes {
		if c.Comment != "" {
			sb.WriteString(fmt.Sprintf("// %s\n", c.Comment))
		}
		sb.WriteString(fmt.Sprintf("export const %s = %s;\n", c.Name, c.Value))
	}

	sb.WriteString("\nexport type GeneratedFrameType =\n")
	for i, f := range frames {
		if i == 0 {
			sb.WriteString(fmt.Sprintf("  | typeof %s\n", f.Name))
		} else {
			sb.WriteString(fmt.Sprintf("  | typeof %s\n", f.Name))
		}
	}
	sb.WriteString(";\n")

	if err := os.MkdirAll(filepath.Dir(outPath), 0755); err != nil {
		return err
	}
	return os.WriteFile(outPath, []byte(sb.String()), 0644)
}

// generateDart emits strongly-typed Dart class constants from protocol definitions.
func generateDart(outPath string, frames, contentTypes []constantDef) error {
	var sb strings.Builder
	sb.WriteString("// Code generated by pulse protogen. DO NOT EDIT.\n\n")

	sb.WriteString("/// Generated wire protocol frame constants.\n")
	sb.WriteString("class GeneratedFrameTypes {\n")
	sb.WriteString("  GeneratedFrameTypes._();\n\n")
	for _, f := range frames {
		if f.Comment != "" {
			sb.WriteString(fmt.Sprintf("  /// %s\n", f.Comment))
		}
		dartName := strings.ToLower(f.Name[:1]) + f.Name[1:]
		sb.WriteString(fmt.Sprintf("  static const int %s = %s;\n", dartName, f.Value))
	}
	sb.WriteString("}\n\n")

	sb.WriteString("/// Generated content type constants.\n")
	sb.WriteString("class GeneratedContentTypes {\n")
	sb.WriteString("  GeneratedContentTypes._();\n\n")
	for _, c := range contentTypes {
		if c.Comment != "" {
			sb.WriteString(fmt.Sprintf("  /// %s\n", c.Comment))
		}
		dartName := strings.ToLower(c.Name[:1]) + c.Name[1:]
		sb.WriteString(fmt.Sprintf("  static const int %s = %s;\n", dartName, c.Value))
	}
	sb.WriteString("}\n")

	if err := os.MkdirAll(filepath.Dir(outPath), 0755); err != nil {
		return err
	}
	return os.WriteFile(outPath, []byte(sb.String()), 0644)
}
